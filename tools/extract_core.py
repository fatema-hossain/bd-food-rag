PRELUDE_NAMES = {"IDX_FILES", "IDX_DIRS", "fratio", "best_match", "torch", "HAS_TORCH", "DEVICE", "GPU", "N_GPU", "LLM_GPU", "HAS_ST", "HAS_TF", "ENV", "PROFILE", "FORCE_SMOKE", "SMOKE",
                 "WORK", "CACHE", "MODEL_DIRS", "MODEL_SOURCES", "INPUT_CACHES", "MODEL_STATUS", "TIMINGS"}
SKIP_DEFS = {"_hf_token", "_build_index", "hf_images_to_folder", "load_foodbd", "synth_foodbd", "synth_meta", "detect_meta_roles",
             "build_domain_kb", "_load_tz", "merge_duplicate_dishes", "_merge_into", "folder_dataset", "foodbd_crops"}
SKIP_ASSIGN = {"ENV", "WORK", "CACHE", "ROOTS", "PROFILE", "FORCE_SMOKE", "DOMAIN_KB_PATH", "DOMAIN_IMG_ROOT", "DOMAIN_TEST_LIST"}

STOP_AT = "def surface(c):"          # first cell of the benchmark section: nothing after it is needed at serving time
def cells_from(path):
    srcs = ["".join(c["source"]) for c in json.load(open(path))["cells"] if c["cell_type"] == "code"] if path.endswith(".ipynb") else [open(path).read()]
    out = []
    for s in srcs:
        if STOP_AT in s: break
        out.append(s)
    return out

def names_in(node):
    load, store = set(), set()
    for n in ast.walk(node):
        if isinstance(n, ast.Name): (store if isinstance(n.ctx, ast.Store) else load).add(n.id)
        elif isinstance(n, ast.arg): store.add(n.arg)
    return load, store

def main(src, out):
    safe = set(dir(builtins)) | PRELUDE_NAMES
    kept, defs, report = [], set(), []
    code = "\n".join(cells_from(src))
    code = "\n".join(l for l in code.splitlines() if not l.lstrip().startswith(("!", "%")))
    tree = ast.parse(code)
    consts = set()
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            kept.append(node); safe |= {(a.asname or a.name).split(".")[0] for a in node.names}
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            if node.name in SKIP_DEFS: continue
            kept.append(node); defs.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            tnames = {n.id for t in targets for n in ast.walk(t) if isinstance(n, ast.Name)}
            if not tnames or any(not isinstance(t, (ast.Name, ast.Tuple)) for t in targets) or tnames & SKIP_ASSIGN: continue
            load, store = names_in(node.value)
            if (load - store) <= (safe | consts) - defs or (isinstance(node, ast.AugAssign) and (load - store) <= (safe | consts)):
                kept.append(node); consts |= tnames
    mod = ast.Module(body=kept, type_ignores=[])
    body = PRELUDE + "\n" + ast.unparse(mod) + "\n"
    open(out, "w").write(body)
    # report globals that kept functions read but nobody defines -> must come from the deploy bundle / runtime
    defined = safe | consts | defs
    free = {}
    for node in kept:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            load, store = names_in(node)
            for nm in load - store - defined:
                free.setdefault(nm, []).append(node.name)
    print(f"kept {sum(isinstance(n, (ast.FunctionDef, ast.ClassDef)) for n in kept)} defs, {len(consts)} constants -> {out}")
    print("globals to supply at runtime:")
    for k in sorted(free): print(f"  {k:22} used by {sorted(set(free[k]))[:6]}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
